"""End-to-end demonstration: runs every scenario plus a resilience drill and writes reviewable evidence."""

from __future__ import annotations

import json
import shutil
from datetime import UTC, datetime
from pathlib import Path

from .approvals import ScenarioApprovals
from .audit import AuditLog
from .metrics import aggregate, to_prometheus
from .runner import Outcome, RunCrashed, get_state, resume, start
from .scenario import load_scenario
from .settings import REPO_ROOT, Settings

# (label, scenario, faults, expected status)
PLAN = [
    ("greenfield", "greenfield", {}, "completed"),
    ("brownfield", "brownfield", {}, "completed"),
    ("ambiguous", "ambiguous", {}, "completed"),
    ("policy-violation", "policy-violation", {}, "halted"),
    ("resilience-drill", "greenfield", {"llm_transient:planning": 2, "invalid_output:design": 1,
                                        "llm_down:documentation": 1, "safe_stop:security_review": 1,
                                        "crash:release": 1}, "completed"),
]


def run_demo(base: Settings, evidence_dir: Path | None = None) -> int:
    stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%S")
    home = base.home / f"demo-{stamp}"
    evidence = evidence_dir or REPO_ROOT / "docs" / "evidence"
    evidence.mkdir(parents=True, exist_ok=True)
    for label, *_ in PLAN:  # replace only what this demo produces; keep e.g. live-claude evidence
        shutil.rmtree(evidence / label, ignore_errors=True)
    rows, ok = [], True
    for label, scenario_name, faults, expected in PLAN:
        settings = base.model_copy(update={"home": home, "faults": dict(faults)})
        scenario = load_scenario(scenario_name)
        run_id = f"{label}-{stamp}"
        print(f"\n=== {label}: {scenario.title} ({scenario.kind}) ===")
        try:
            outcome = start(scenario, settings, ScenarioApprovals(scenario), run_id)
        except RunCrashed as exc:
            print(f"  crashed as injected ({exc}); operator resumes from checkpoint")
            outcome = resume(run_id, settings, ScenarioApprovals(scenario))
        rows.append(_collect(label, scenario.kind, settings, outcome, evidence / label))
        passed = outcome.status == expected
        ok &= passed
        print(f"  -> {outcome.status} (expected {expected}) {'OK' if passed else 'UNEXPECTED'}")

    agg = aggregate(home)
    (evidence / "metrics.json").write_text(json.dumps(agg, indent=2))
    (evidence / "metrics.prom").write_text(to_prometheus(agg))
    (evidence / "README.md").write_text(_index(rows, agg, stamp, evidence))
    print(f"\nEvidence written to {evidence}")
    return 0 if ok else 1


def _collect(label: str, kind: str, settings: Settings, outcome: Outcome, out: Path) -> dict:
    run_dir = settings.run_dir(outcome.run_id)
    out.mkdir(parents=True)
    state, _ = get_state(outcome.run_id, settings)
    verify = AuditLog.verify(run_dir / "audit.jsonl")
    for src, dst in [("release/ENGINEERING_SUMMARY.md", "ENGINEERING_SUMMARY.md"),
                     ("release/change.patch", "change.patch"), ("release/traceability.json", "traceability.json"),
                     ("metrics.json", "metrics.json"), ("audit.jsonl", "audit.jsonl")]:
        if (run_dir / src).exists():
            shutil.copy2(run_dir / src, out / dst)
    for log in sorted((run_dir / "logs").glob("*.log")):
        lines = log.read_text().splitlines()
        (out / log.name).write_text("\n".join(lines[-60:]) + "\n")
    ver = state.get("artifacts", {}).get("verification", {})
    return {"label": label, "kind": kind, "run_id": outcome.run_id, "status": outcome.status,
            "path": " -> ".join(state.get("path", [])), "tests": ver.get("tests", "-"),
            "failures": ver.get("failures", "-"), "rework": state.get("rework_count", 0),
            "approvals": len(state.get("approvals", {})), "audit": f"{'valid' if verify.ok else 'INVALID'} "
                                                                   f"({verify.records} records)",
            "halt": (outcome.halt or {}).get("reason", ""), "metrics": outcome.metrics}


def _index(rows: list[dict], agg: dict, stamp: str, evidence_root: Path | None = None) -> str:
    lines = [
        "# Execution evidence", "",
        f"Generated by `agentic demo` at {stamp} (UTC). Every run below executed the real orchestration graph, applied "
        "the generated change set to a sandbox copy of `url-shortener/`, and ran the real Maven build and test suite. "
        "LLM responses were replayed from the scenario recordings (offline mode), so the run is reproducible without "
        "API keys; set `ANTHROPIC_API_KEY` and use `--llm claude` for live generation.", "",
        "| Scenario | Kind | Outcome | Tests run (failures, final round) | Rework cycles | Human decisions "
        "| Audit chain |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(f"| [{r['label']}]({r['label']}/ENGINEERING_SUMMARY.md) | {r['kind']} | **{r['status']}** "
                     f"{('- ' + r['halt']) if r['halt'] else ''} | {r['tests']} ({r['failures']}) | {r['rework']} | "
                     f"{r['approvals']} | {r['audit']} |")
    live = evidence_root / "live-claude" / "metrics.json" if evidence_root else None
    if live and live.exists():
        m = json.loads(live.read_text())
        lines += ["", "## Live LLM run (Claude, no recorded responses)", "",
                  "[live-claude](live-claude/ENGINEERING_SUMMARY.md): ad-hoc requirement (no recordings, so Claude was "
                  "the only provider). Every artifact - spec, clarification questions, plan, two design revisions, "
                  "code, tests and docs - was generated live by `claude-opus-5-5`. "
                  f"Outcome **{m['run_status']}**, LLM calls by provider {m['llm_calls_by_provider']}, "
                  f"fallbacks {m['fallbacks']}, retries {m['retries']}."]
    lines += ["", "## Execution paths (actual, including loops)", ""]
    lines += [f"- **{r['label']}**: {r['path']}" for r in rows]
    lines += ["", "## Reliability metrics (aggregate over these runs)", "", "```json",
              json.dumps({k: v for k, v in agg.items() if k != "per_run"}, indent=2), "```", "",
              "Per-run metrics, audit logs (`audit.jsonl`, hash-chained - verify with `agentic audit verify`), "
              "patches, traceability matrices and build-log tails are in each scenario folder."]
    return "\n".join(lines) + "\n"
