CREATE TABLE links (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(32)   NOT NULL,
    target_url      VARCHAR(2048) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at      TIMESTAMP WITH TIME ZONE,
    active          BOOLEAN       NOT NULL DEFAULT TRUE,
    idempotency_key VARCHAR(128),
    click_count     BIGINT        NOT NULL DEFAULT 0,
    version         BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_links_code UNIQUE (code),
    CONSTRAINT uk_links_idempotency_key UNIQUE (idempotency_key)
);

CREATE TABLE click_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_id       BIGINT       NOT NULL,
    clicked_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    referrer_host VARCHAR(255),
    visitor_hash  VARCHAR(64)  NOT NULL,
    CONSTRAINT fk_click_events_link FOREIGN KEY (link_id) REFERENCES links (id) ON DELETE CASCADE
);

CREATE INDEX idx_click_events_link_time ON click_events (link_id, clicked_at);
